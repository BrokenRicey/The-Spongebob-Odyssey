"""Turn the bundled Houston routes into an explicitly assumed study network.

Only coincident endpoints of equal voltage are joined. Route crossings and
nearby, differently rated endpoints do not establish electrical connections.
The fixed equivalent supplies below make each initial component studyable;
they are not identified utility sources and are never regenerated by a solve.
"""
import json
import math
from pathlib import Path

from map.generator import DEFAULT_BBOX, build_features, length_km
from simulation.gridsim.config import LINE_PARAMETERS, LIMITS

ROOT = Path(__file__).resolve().parents[1]
ENDPOINT_TOLERANCE_M = 1.0


def _route_key(feature):
    properties = feature['properties']
    for key in ('OBJECTID', 'OBJECTID_1', 'ID'):
        if properties.get(key) is not None:
            return str(properties[key])
    raise ValueError('Every imported route needs a stable source identifier.')


def import_features(features, bbox=DEFAULT_BBOX, provenance=None):
    """Build fresh topology and fixed initial supplies from GeoJSON features.

    This is an import operation, not an operation to repeat after an edit/run.
    The caller owns the returned model, including every source in its snapshot.
    """
    features = sorted(features, key=_route_key)
    keys = [_route_key(feature) for feature in features]
    if len(set(keys)) != len(keys):
        raise ValueError('Duplicate source route identifiers.')
    endpoints, routes = [], []
    west, south, east, north = bbox
    scale_x = 6371008.8 * math.pi / 180 * math.cos(math.radians((south+north)/2))
    scale_y = 6371008.8 * math.pi / 180
    unknown_voltage = []
    for feature in features:
        key, properties = _route_key(feature), feature['properties']
        voltage = properties.get('VOLTAGE')
        if isinstance(voltage, bool) or not isinstance(voltage, (int, float)) or not math.isfinite(voltage) or voltage <= 0:
            voltage = 138.0
            unknown_voltage.append(key)
        parts = feature['geometry']['coordinates']
        if feature['geometry']['type'] == 'LineString':
            parts = [parts]
        elif feature['geometry']['type'] != 'MultiLineString':
            raise ValueError('Only transmission line geometry can be imported.')
        for index, part in enumerate(parts, 1):
            if len(part) < 2 or length_km([part]) <= 0:
                raise ValueError(f'Route {key}, part {index} has no usable length.')
            line_id = f'GIS_{key}_{index}'
            start = len(endpoints)
            for end, point in zip(('A', 'B'), (part[0], part[-1])):
                lon, lat = point[:2]
                boundary = min(abs(lon-west)*scale_x, abs(lon-east)*scale_x,
                               abs(lat-south)*scale_y, abs(lat-north)*scale_y) <= ENDPOINT_TOLERANCE_M
                endpoints.append(dict(token=f'{line_id}_{end}', lon=lon, lat=lat,
                                      x=lon*scale_x, y=lat*scale_y, voltage=voltage, boundary=boundary))
            routes.append((line_id, key, index, part, properties, start, voltage))
    if not endpoints:
        raise ValueError('No usable transmission routes in this study area.')

    parent = list(range(len(endpoints)))

    def find(index):
        while parent[index] != index:
            parent[index] = parent[parent[index]]
            index = parent[index]
        return index

    # Spatial buckets avoid a quadratic scan; unions remain deterministic.
    buckets = {}
    for index, point in enumerate(endpoints):
        cell_x, cell_y = math.floor(point['x']), math.floor(point['y'])
        for x in range(cell_x-1, cell_x+2):
            for y in range(cell_y-1, cell_y+2):
                for other in buckets.get((point['voltage'], x, y), ()):
                    candidate = endpoints[other]
                    if math.hypot(point['x']-candidate['x'], point['y']-candidate['y']) <= ENDPOINT_TOLERANCE_M:
                        a, b = find(index), find(other)
                        parent[max(a, b)] = min(a, b)
        buckets.setdefault((point['voltage'], cell_x, cell_y), []).append(index)
    groups = {}
    for index in range(len(endpoints)):
        groups.setdefault(find(index), []).append(index)
    buses, bus_for_endpoint = [], {}
    for indices in groups.values():
        point = endpoints[min(indices)]
        bus = dict(id='BUS_'+point['token'], lat=point['lat'], lon=point['lon'],
                   vn_kv=point['voltage'], in_service=True, value_status='assumed',
                   boundary_interface=any(endpoints[i]['boundary'] for i in indices),
                   connection_assumption='Same-voltage GIS endpoints within 1 m are assumed connected.')
        buses.append(bus)
        for index in indices:
            bus_for_endpoint[index] = bus['id']

    lines = []
    adjacency = {bus['id']: set() for bus in buses}
    for line_id, key, part_number, part, properties, start, voltage in routes:
        a, b = bus_for_endpoint[start], bus_for_endpoint[start+1]
        if a == b:
            raise ValueError(f'{line_id} becomes a closed loop after endpoint merging; split its route before import.')
        line = dict(LINE_PARAMETERS, id=line_id, from_bus=a, to_bus=b,
                    length_km=length_km([part]), in_service=True,
                    points=[[point[1], point[0]] for point in part],
                    source_route_key=key, source_part=part_number,
                    source_line_id=str(properties.get('ID', key)),
                    owner=properties.get('OWNER', 'Unknown'), vn_kv=voltage,
                    source_voltage_kv=properties.get('VOLTAGE'),
                    value_status='assumed', source_geometry=True,
                    parameter_assumption='V4 demonstration R/X/current rating; route length follows cached GIS geometry.')
        lines.append(line)
        adjacency[a].add(b)
        adjacency[b].add(a)

    bus_lookup = {bus['id']: bus for bus in buses}
    visited, sources, component_sizes = set(), [], []
    for bus_id in sorted(adjacency):
        if bus_id in visited:
            continue
        component, pending = [], [bus_id]
        visited.add(bus_id)
        while pending:
            current = pending.pop()
            component.append(current)
            for neighbor in sorted(adjacency[current]):
                if neighbor not in visited:
                    visited.add(neighbor)
                    pending.append(neighbor)
        chosen = min(component, key=lambda key: (not bus_lookup[key]['boundary_interface'], -len(adjacency[key]), key))
        component_id = f'INITIAL_COMPONENT_{len(sources)+1:03d}'
        for key in component:
            bus_lookup[key]['initial_component'] = component_id
        sources.append(dict(id=f'SUPPLY_{len(sources)+1:03d}', bus_id=chosen,
                            vm_pu=1.02, in_service=True, value_status='assumed',
                            initial_component=component_id,
                            connection_assumption='Fixed equivalent external supply for this initial GIS component; not a verified utility source.',
                            boundary_interface=bus_lookup[chosen]['boundary_interface']))
        component_sizes.append(len(component))

    assumptions = [
        'All visible cached Houston routes participate in the power-flow study. Geography is sourced; electrical connectivity and equipment parameters are assumed.',
        'Only same-voltage route endpoints within 1 m are joined. Crossings are not connected; no inter-voltage transformers are inferred.',
        'Exactly one fixed equivalent external supply is assumed per initial connected component, preferring a clipped boundary endpoint. Separate components and voltage groups remain independent.',
        'Sources are saved equipment. Disabling or disconnecting equipment never creates a replacement source; islands may become unsupplied.',
        'Line resistance 0.05 ohm/km, reactance 0.40 ohm/km, capacitance zero and current rating 1 kA are demonstration assumptions, not utility measurements.',
        'Missing/invalid source voltage is assumed 138 kV and recorded in source metadata.',
        'Initial data centers are synthetic 10 MW study loads using earlier study coordinates, not verified facilities or demand. Their demand is editable.',
        'Data-center demand is referred to its connection voltage with an assumed ideal, adequately rated site interface; internal losses are omitted.',
    ]
    return dict(name='Houston geographic editable study · Project V4', model_version=4,
                buses=buses, lines=lines, transformers=[], sources=sources, loads=[],
                limits=dict(LIMITS), assumptions=assumptions,
                provenance=dict(provenance or {}, network_kind='GIS-derived assumed electrical study',
                                source_feature_count=len(features), source_part_count=len(routes),
                                imported_bus_count=len(buses), initial_component_count=len(sources),
                                initial_component_bus_counts=component_sizes,
                                endpoint_tolerance_m=ENDPOINT_TOLERANCE_M,
                                assumed_voltage_route_keys=unknown_voltage))


def build_houston_model(seed_loads=True):
    """Import the bundled snapshot; edits and project reopening must retain it."""
    cache_path = ROOT/'map/assets/source_cache.json'
    cache = json.loads(cache_path.read_text(encoding='utf-8'))
    features = build_features(cache, DEFAULT_BBOX)['features']
    model = import_features(features, provenance={
        'source_url': cache['layer_url'], 'retrieved_utc': cache['retrieved_utc'],
        'bbox': list(DEFAULT_BBOX), 'cache': 'map/assets/source_cache.json',
    })
    if seed_loads:
        from simulation.editor import add_datacenter
        previous = json.loads((ROOT/'data/model/houston_model.json').read_text(encoding='utf-8'))
        locations = {bus['id']: bus for bus in previous['buses']}
        for old in previous['loads']:
            site = locations[old['bus_id']]
            load = add_datacenter(model, old['id'], site['lat'], site['lon'], 10.0, old['pf'], old.get('onsite_gen_mw', 0))
            load.update(value_status='synthetic', coordinate_source='Earlier synthetic study bus location; not a verified data center.')
    return model


def default_houston_model():
    """Application entry point for a new full Houston geographic study."""
    return build_houston_model()
